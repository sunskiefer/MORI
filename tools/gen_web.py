#!/usr/bin/env python3
"""Writes src/mori_web_data.h: the editor page and the parameter description, as byte arrays for the engine's web server."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, "params.json")))
ps = []
for i, p in enumerate(d["params"]):
    e = {"i": i, "k": p["key"], "n": p.get("name", p["key"])}
    if p.get("options"): e["o"] = p["options"]
    else: e["min"] = p.get("min", 0); e["max"] = p.get("max", 1)
    if p.get("display") == "int": e["int"] = 1
    if p.get("display") == "string": e["str"] = 1
    if p.get("unit"): e["u"] = p["unit"]
    if p.get("momentary"): e["trig"] = 1
    ps.append(e)
meta = json.dumps({"p": ps, "secs": d["sections"]}, separators=(",", ":")).encode()
page = open(os.path.join(root, "web", "editor.html"), "rb").read()
def arr(name, b):
    return "static const unsigned char %s[] = {%s};\nstatic const unsigned %s_LEN = %d;\n" % (name, ",".join(str(x) for x in b), name, len(b))
open(os.path.join(root, "src", "mori_web_data.h"), "w").write("/* generated by tools/gen_web.py: do not edit */\n#pragma once\n" + arr("WEB_META", meta) + arr("WEB_PAGE", page))
print("web data:", len(meta), "bytes meta,", len(page), "bytes page")
